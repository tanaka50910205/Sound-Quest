//   key   : a に正解の鍵盤（MIDI番号）。2つ以上なら全部押す問題。鍵盤は 60（ド）〜76（ミ）
//   order : tiles を正しい順で書く。extra はまぎらわしい札
//   listen: 生成関数で作る（毎回ランダム）。play に鳴らす音、o の a 番目が正解
//   ex    : 答えたあとに出す解説

const NOTE_JP = ['ド', 'ド♯', 'レ', 'ミ♭', 'ミ', 'ファ', 'ファ♯', 'ソ', 'ソ♯', 'ラ', 'シ♭', 'シ'];
const NOTE_EN = ['C', 'C♯', 'D', 'E♭', 'E', 'F', 'F♯', 'G', 'A♭', 'A', 'B♭', 'B'];

const rnd = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const chordName = (root, suffix) => NOTE_EN[root % 12] + suffix;

